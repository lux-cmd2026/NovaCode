const dicts: Record<Lang, Dict> = { en, zh }

export function t(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? en[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
  return s
}

/**
 * Turn an error thrown in the main process into a localized sentence.
 * Codes look like `CODEX_PORT_BUSY` or `CODEX_LOGIN_DENIED:access_denied`.
 */
export function localizeError(lang: Lang, message: string, vars?: Record<string, string | number>): string {
  const m = message.match(/^(CODEX_[A-Z_]+?)(?:_(\d{3}))?(?::(.*))?$/)
  if (!m) return message
  const [, base, http, extra] = m
  const key = 'err.' + (http ? base.replace(/_HTTP$/, '') + '_HTTP' : base)
  const hasKey = dicts[lang][key] || en[key]
  if (!hasKey) return message
  return t(lang, key, { code: http ?? extra ?? '', ...vars })
}
